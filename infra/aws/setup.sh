#!/usr/bin/env bash
# Sets up one EC2 server (Ubuntu 24.04) for the AIOps lab.
#
# Run on the server AFTER `sudo tailscale up` has connected it:
#   sudo bash setup.sh database <LAPTOP_TS_IP>
#   sudo bash setup.sh backend  <LAPTOP_TS_IP> <DATABASE_TS_IP>
#   sudo bash setup.sh frontend <LAPTOP_TS_IP> <BACKEND_TS_IP>
#
# Optional: DB_PASSWORD=... (must be the same on database and backend; default "devops").
# Safe to re-run.
set -euo pipefail

ROLE="${1:-}"; MONITOR_IP="${2:-}"; TARGET_IP="${3:-}"
DB_PASSWORD="${DB_PASSWORD:-devops}"
APP_USER="${SUDO_USER:-ubuntu}"
APP_UID="$(id -u "$APP_USER")"
APP_HOME="$(getent passwd "$APP_USER" | cut -d: -f6)"

usage() { echo "Usage: sudo bash setup.sh <frontend|backend|database> <LAPTOP_TS_IP> [TARGET_TS_IP]"; exit 1; }
[[ $EUID -eq 0 ]] || { echo "Run with sudo."; exit 1; }
case "$ROLE" in frontend|backend|database) ;; *) usage ;; esac
[[ -n "$MONITOR_IP" ]] || usage
if [[ "$ROLE" != "database" && -z "$TARGET_IP" ]]; then
  echo "$ROLE needs a third argument: the Tailscale IP of the $( [[ $ROLE == backend ]] && echo database || echo backend ) server."; exit 1
fi

HOST_LABEL="${ROLE^}"   # Frontend / Backend / Database: must match the Zabbix host and Loki "host" label
log() { echo -e "\n==> $*"; }
as_user() { sudo -u "$APP_USER" XDG_RUNTIME_DIR="/run/user/$APP_UID" "$@"; }

log "Hostname and 1 GB swap (free-tier servers only have ~1 GB RAM)"
hostnamectl set-hostname "$ROLE"
if ! swapon --show | grep -q /swapfile; then
  fallocate -l 1G /swapfile && chmod 600 /swapfile && mkswap /swapfile && swapon /swapfile
  grep -q '^/swapfile' /etc/fstab || echo '/swapfile none swap sw 0 0' >> /etc/fstab
fi

log "Base packages"
export DEBIAN_FRONTEND=noninteractive
apt-get update -q
apt-get install -y -q curl gnupg ca-certificates

log "Zabbix agent 2 (active checks to the laptop)"
if ! dpkg -s zabbix-agent2 >/dev/null 2>&1; then
  if curl -fsSLo /tmp/zabbix-release.deb \
      "https://repo.zabbix.com/zabbix/7.0/ubuntu/pool/main/z/zabbix-release/zabbix-release_latest_7.0+ubuntu24.04_all.deb"; then
    dpkg -i /tmp/zabbix-release.deb && apt-get update -q
  else
    echo "Zabbix 7.0 repo not reachable; using Ubuntu's own zabbix-agent2 (older agents still work with server 7.0)."
  fi
  apt-get install -y -q zabbix-agent2
fi
ZCONF=/etc/zabbix/zabbix_agent2.conf
sed -i -E "s|^#? ?Server=.*|Server=${MONITOR_IP}|; s|^#? ?ServerActive=.*|ServerActive=${MONITOR_IP}|; s|^#? ?Hostname=.*|Hostname=${HOST_LABEL}|" "$ZCONF"
grep -q '^HostMetadata=' "$ZCONF" || echo 'HostMetadata=aiops-lab' >> "$ZCONF"
systemctl enable --now zabbix-agent2 && systemctl restart zabbix-agent2

log "Grafana Alloy (ships logs to Loki on the laptop)"
if ! dpkg -s alloy >/dev/null 2>&1; then
  mkdir -p /etc/apt/keyrings
  curl -fsSL https://apt.grafana.com/gpg.key | gpg --dearmor --yes -o /etc/apt/keyrings/grafana.gpg
  echo "deb [signed-by=/etc/apt/keyrings/grafana.gpg] https://apt.grafana.com stable main" > /etc/apt/sources.list.d/grafana.list
  apt-get update -q && apt-get install -y -q alloy
fi
usermod -aG systemd-journal,adm alloy   # read the journal (incl. container logs) and nginx logs

NGINX_BLOCK=""
if [[ "$ROLE" == "frontend" ]]; then
  NGINX_BLOCK=$(cat <<EOF

local.file_match "nginx" {
  path_targets = [{"__path__" = "/var/log/nginx/*.log", host = "${HOST_LABEL}", job = "nginx"}]
}
loki.source.file "nginx" {
  targets    = local.file_match.nginx.targets
  forward_to = [loki.write.laptop.receiver]
}
EOF
)
fi

cat > /etc/alloy/config.alloy <<EOF
// Generated by infra/aws/setup.sh for ${HOST_LABEL}
loki.relabel "journal" {
  forward_to = []
  rule {
    source_labels = ["__journal__systemd_unit"]
    target_label  = "unit"
  }
  rule {
    source_labels = ["__journal_container_name"]
    target_label  = "container"
  }
  rule {
    source_labels = ["__journal_priority_keyword"]
    target_label  = "level"
  }
}

loki.source.journal "system" {
  forward_to    = [loki.write.laptop.receiver]
  relabel_rules = loki.relabel.journal.rules
  max_age       = "12h"
  labels        = {host = "${HOST_LABEL}", job = "journal"}
}
${NGINX_BLOCK}

loki.write "laptop" {
  endpoint {
    url = "http://${MONITOR_IP}:3100/loki/api/v1/push"
  }
}
EOF
systemctl enable --now alloy && systemctl restart alloy

if [[ "$ROLE" != "frontend" ]]; then
  log "Podman (rootless, for user $APP_USER) with the docker command alias"
  apt-get install -y -q podman podman-docker
  touch /etc/containers/nodocker   # silence the "emulating docker" notice
  mkdir -p /etc/containers/registries.conf.d
  cat > /etc/containers/registries.conf.d/00-dockerhub.conf <<'EOF'
unqualified-search-registries = ["docker.io"]
short-name-mode = "permissive"
EOF
  loginctl enable-linger "$APP_USER"     # keep containers running without a login session
  for _ in $(seq 1 10); do [[ -d /run/user/$APP_UID ]] && break; sleep 1; done
  # Restart containers with restart policies after a reboot.
  as_user systemctl --user enable podman-restart.service || true
fi

case "$ROLE" in
database)
  log "PostgreSQL 16 container 'postgres' (host network, port 5432)"
  as_user podman rm -f postgres >/dev/null 2>&1 || true
  as_user podman run -d --name postgres --restart=always --network host \
    --log-driver journald \
    -e POSTGRES_DB=devops_demo -e POSTGRES_USER=devops -e POSTGRES_PASSWORD="$DB_PASSWORD" \
    -v pgdata:/var/lib/postgresql/data \
    docker.io/library/postgres:16-alpine
  ;;
backend)
  SHOP_DIR="$APP_HOME/devops-demo-shop"
  [[ -f "$SHOP_DIR/Dockerfile" ]] || { echo "Copy devops-demo-shop to $SHOP_DIR first (see README)."; exit 1; }
  log "Building the shop image (takes a few minutes on a micro server)"
  as_user podman build -t localhost/devops-demo-shop:latest "$SHOP_DIR"
  log "Shop container 'devops-demo-app' (host network, port 8000)"
  as_user podman rm -f devops-demo-app >/dev/null 2>&1 || true
  as_user podman run -d --name devops-demo-app --restart=always --network host \
    --log-driver journald \
    -e DATABASE_URL="postgresql://devops:${DB_PASSWORD}@${TARGET_IP}:5432/devops_demo" \
    -e ENABLE_FAULTS=true -e LOG_LEVEL=INFO \
    localhost/devops-demo-shop:latest
  ;;
frontend)
  log "Nginx reverse proxy to the backend"
  apt-get install -y -q nginx
  cat > /etc/nginx/sites-available/default <<EOF
server {
    listen 80 default_server;
    server_name _;

    location /nginx_status {
        stub_status;
        allow 127.0.0.1;
        deny all;
    }

    location / {
        proxy_pass http://${TARGET_IP}:8000;
        proxy_set_header Host \$host;
        proxy_set_header X-Real-IP \$remote_addr;
        proxy_set_header X-Forwarded-For \$proxy_add_x_forwarded_for;
        proxy_connect_timeout 5s;
        proxy_read_timeout 60s;
    }
}
EOF
  nginx -t && systemctl enable --now nginx && systemctl reload nginx
  ;;
esac

log "Done: ${HOST_LABEL}"
echo "Tailscale IP: $(tailscale ip -4 2>/dev/null || echo 'tailscale not connected!')"
case "$ROLE" in
  database) echo "Check: sudo -u $APP_USER docker inspect -f '{{.State.Status}}' postgres" ;;
  backend)  sleep 5; echo -n "Health: "; curl -s --max-time 10 http://127.0.0.1:8000/api/health || echo "not ready yet (check: docker logs devops-demo-app)" ;;
  frontend) echo -n "Through nginx: "; curl -s -o /dev/null -w '%{http_code}\n' --max-time 10 http://127.0.0.1/ ;;
esac
